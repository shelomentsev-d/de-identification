def filter_overlaps(spans: list[Span]) -> list[Span]:
    """Keep non-overlapping spans, preferring earlier and longer spans."""
    ordered = sorted(spans, key=lambda span: (span[0], -(span[1] - span[0])))
    result: list[Span] = []
    last_end = -1
    for span in ordered:
        if span[2] == "__PREFIX__":
            last_end = max(last_end, span[1])
            continue
        if span[0] >= last_end:
            result.append(span)
            last_end = span[1]
    return result
